"""Per-column data profile and V-column pruning proposal (Step 2).

Everything is computed on the training block only (first 80% by time, rows 0..472,431),
so the validation and test blocks stay out of the V-column decision.
"""
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

from src.data import ROOT, load_joined

N_TRAIN = 472_432          # train = rows 0 to 472,431 (Context.md: first 80% by time)
CORR_THRESHOLD = 0.9
V_COLS = [f"V{i}" for i in range(1, 340)]
FEATURES_YAML = ROOT / "config" / "features.yaml"
REPORT_PATH = ROOT / "reports" / "data_profile.md"


def train_block(df):
    return df.iloc[:N_TRAIN]


def column_profile(train):
    """dtype, % missing, distinct count and fraud rate when missing vs present, per column."""
    fraud = train["isFraud"].to_numpy()
    rows = []
    for col in train.columns:
        s = train[col]
        miss = s.isna().to_numpy()
        n_miss = int(miss.sum())
        rows.append({
            "column": col,
            "dtype": str(s.dtype),
            "pct_missing": 100 * n_miss / len(s),
            "n_distinct": int(s.nunique(dropna=True)),
            "fraud_rate_missing": fraud[miss].mean() if n_miss else np.nan,
            "fraud_rate_present": fraud[~miss].mean() if n_miss < len(s) else np.nan,
        })
    out = pd.DataFrame(rows)
    return out.sort_values("pct_missing", ascending=False, kind="stable").reset_index(drop=True)


def v_groups(train):
    """Group V columns by identical missing count. Returns {n_missing: [cols in V order]}."""
    counts = train[V_COLS].isna().sum()
    groups = {}
    for col in V_COLS:
        groups.setdefault(int(counts[col]), []).append(col)
    return dict(sorted(groups.items()))


def prune_group(train, cols, threshold=CORR_THRESHOLD):
    """Greedy prune: visit columns by distinct count (desc, ties in V order); keep a column
    unless |r| > threshold with one already kept. Returns (keep, drop, dropped_because)."""
    nun = {c: train[c].nunique(dropna=True) for c in cols}
    order = sorted(cols, key=lambda c: (-nun[c], cols.index(c)))
    corr = train[cols].astype("float64").corr().abs()
    keep, drop, because = [], [], {}
    for c in order:
        clash = [k for k in keep if corr.loc[c, k] > threshold]
        if clash:
            drop.append(c)
            because[c] = clash[0]
        else:
            keep.append(c)
    v_order = {c: i for i, c in enumerate(V_COLS)}
    return sorted(keep, key=v_order.get), sorted(drop, key=v_order.get), because


def v_proposal(train):
    groups = v_groups(train)
    result = []
    for i, (n_miss, cols) in enumerate(groups.items(), start=1):
        keep, drop, because = prune_group(train, cols)
        masks = train[cols].isna().T.drop_duplicates()
        result.append({"group": i, "n_missing": n_miss, "pct_missing": 100 * n_miss / len(train),
                       "columns": cols, "keep": keep, "drop": drop, "because": because,
                       "same_mask": len(masks) == 1})
    return result


def write_features_yaml(proposal, path=FEATURES_YAML):
    keep = [c for g in proposal for c in g["keep"]]
    drop = [c for g in proposal for c in g["drop"]]
    order = {c: i for i, c in enumerate(V_COLS)}
    doc = {"v_columns_proposed": {
        "status": "proposed, awaiting group approval",
        "rule": f"groups = identical missing count on train block; within a group drop one of any "
                f"pair with |Pearson r| > {CORR_THRESHOLD}, keeping the column with more distinct values",
        "keep": sorted(keep, key=order.get),
        "drop": sorted(drop, key=order.get),
    }}
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as f:
        yaml.safe_dump(doc, f, sort_keys=False, default_flow_style=None, width=100)


def _fmt(x, pct=False):
    if pd.isna(x):
        return "n/a"
    return f"{x:.2f}" if pct else f"{100 * x:.2f}%"


def write_report(prof, proposal, fraud_rate, path=REPORT_PATH):
    n_keep = sum(len(g["keep"]) for g in proposal)
    n_drop = sum(len(g["drop"]) for g in proposal)
    lines = [
        "# Data profile",
        "",
        f"Computed on the training block (first {N_TRAIN:,} rows by time, 80%). The validation and test "
        "blocks are not used. Generated by `src/data_profile.py` (see section 3 of `notebooks/01_eda.ipynb`).",
        "",
        f"- Columns profiled: {len(prof)}",
        f"- Train fraud rate: {100 * fraud_rate:.2f}%. A column with no missing values shows `n/a` for fraud-when-missing.",
        f"- V columns: {len(V_COLS)} in {len(proposal)} groups; proposal keeps {n_keep}, drops {n_drop}.",
        "",
        "## V-column groups",
        "",
        "Groups share an identical missing count. `same mask` says whether the missing rows are also identical.",
        "",
        "| Group | % missing | Columns | Keep | Drop | Same mask |",
        "| ---: | ---: | ---: | ---: | ---: | :---: |",
    ]
    for g in proposal:
        lines.append(f"| {g['group']} | {g['pct_missing']:.2f} | {len(g['columns'])} | {len(g['keep'])} "
                     f"| {len(g['drop'])} | {'yes' if g['same_mask'] else 'no'} |")
    lines += ["", "### Keep and drop lists per group", ""]
    for g in proposal:
        lines.append(f"**Group {g['group']}** ({g['pct_missing']:.2f}% missing, {len(g['columns'])} columns)")
        lines.append(f"- keep: {', '.join(g['keep'])}")
        lines.append(f"- drop: {', '.join(f'{c} (r with {k})' for c, k in g['because'].items()) or 'none'}")
        lines.append("")
    lines += [
        "## Per-column profile",
        "",
        "Sorted by % missing (highest first). Fraud rates are percentages of train rows.",
        "",
        "| Column | dtype | % missing | Distinct | Fraud % when missing | Fraud % when present |",
        "| --- | --- | ---: | ---: | ---: | ---: |",
    ]
    for r in prof.itertuples():
        lines.append(f"| {r.column} | {r.dtype} | {r.pct_missing:.2f} | {r.n_distinct:,} "
                     f"| {_fmt(r.fraud_rate_missing)} | {_fmt(r.fraud_rate_present)} |")
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text("\n".join(lines) + "\n")


def run():
    train = train_block(load_joined())
    prof = column_profile(train)
    proposal = v_proposal(train)
    write_report(prof, proposal, train['isFraud'].mean())
    write_features_yaml(proposal)
    return prof, proposal


if __name__ == "__main__":
    prof, proposal = run()
    print(f"columns={len(prof)} groups={len(proposal)}")
    for g in proposal:
        print(g["group"], f"{g['pct_missing']:.1f}%", len(g["columns"]), "keep", len(g["keep"]),
              "drop", len(g["drop"]), "same_mask", g["same_mask"])
    print("keep", sum(len(g["keep"]) for g in proposal), "drop", sum(len(g["drop"]) for g in proposal))
