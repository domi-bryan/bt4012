"""4 x 3 validation grid summary from results/log.csv (Step 11).

Every number in the report is computed from the log's validation rows; nothing is typed in.
Run `.venv/bin/python -m src.summarise` to regenerate reports/grid_validation.md.
"""
import pandas as pd

from src.data import ROOT
from src.results import LOG_PATH

REPORT_PATH = ROOT / "reports" / "grid_validation.md"
MODELS = {"logreg": "LR", "rf": "RF", "lgbm": "LightGBM", "mlp": "MLP"}
FEATURE_SETS = ["F0", "F1", "F2"]
METRICS = {"pr_auc": "PR-AUC", "auroc": "AUROC", "recall_top1pct": "Recall in top 1%"}
SEEDS = [0, 1, 2]


def validation_grid(log):
    """Mean, sample std and seed count per (model, feature set) from validation rows.

    Raises if a cell is missing, lacks one of seeds 0-2, or has a repeated seed, so the table
    can never silently average over reruns or partial results.
    """
    val = log[(log["split"] == "val") & log["model"].isin(MODELS)
              & log["feature_set"].isin(FEATURE_SETS)]
    problems = []
    for model in MODELS:
        for fs in FEATURE_SETS:
            seeds = sorted(val.loc[(val.model == model) & (val.feature_set == fs), "seed"])
            if seeds != SEEDS:
                problems.append(f"{model}/{fs}: seeds {seeds}")
    if problems:
        raise ValueError("Validation rows must be exactly seeds 0, 1, 2 per cell: " + "; ".join(problems))
    return val.groupby(["model", "feature_set"])[list(METRICS)].agg(["mean", "std", "count"])


def metric_table(grid, metric):
    """Rows = models, columns = feature sets, plus the two derived gains (means only)."""
    mean = grid[(metric, "mean")].unstack("feature_set").loc[list(MODELS), FEATURE_SETS]
    std = grid[(metric, "std")].unstack("feature_set").loc[list(MODELS), FEATURE_SETS]
    gain_model = mean.loc["lgbm"] - mean.loc["logreg"]          # LR -> LightGBM, per feature set
    gain_features = mean["F2"] - mean["F0"]                      # F0 -> F2, per model
    return mean, std, gain_model, gain_features


def _cell(m, s):
    return f"{m:.4f} ± {s:.4f}"


def _gain(g, base):
    return f"{g:+.4f} ({100 * g / base:+.1f}%)"


def render(log, log_path=LOG_PATH):
    grid = validation_grid(log)
    val = log[log["split"] == "val"]
    source = log_path.relative_to(ROOT) if log_path.is_relative_to(ROOT) else log_path
    lines = [
        "# Validation grid (Step 11)",
        "",
        f"Generated by `.venv/bin/python -m src.summarise` from `{source}` "
        f"({len(val)} validation rows; run dates {', '.join(sorted(val['date'].astype(str).unique()))}). "
        "Each cell is the mean ± sample standard deviation over seeds 0, 1, 2 on the validation block "
        "(the 10% after the train block). LR is deterministic, so its std is 0. "
        "No test-block rows are used.",
        "",
        "Results are provisional until the group approves the V-column list (`config/features.yaml`). "
        "LightGBM and the MLP use the validation block for early stopping, so their validation "
        "scores are not independent of model fitting.",
        "",
        "Derived rows: **LR → LightGBM** is LightGBM's mean minus LR's mean for each feature set "
        "(the model-complexity gain). **F0 → F2** (last column) is each model's F2 mean minus its "
        "F0 mean (the customer-history gain). Relative change in brackets.",
    ]
    for metric, label in METRICS.items():
        mean, std, gain_model, gain_features = metric_table(grid, metric)
        lines += ["", f"## {label}", "",
                  "| Model | F0 | F1 | F2 | F0 → F2 |", "| --- | --- | --- | --- | --- |"]
        for model, name in MODELS.items():
            cells = [_cell(mean.loc[model, fs], std.loc[model, fs]) for fs in FEATURE_SETS]
            lines.append(f"| {name} | {' | '.join(cells)} | {_gain(gain_features[model], mean.loc[model, 'F0'])} |")
        gains = [_gain(gain_model[fs], mean.loc["logreg", fs]) for fs in FEATURE_SETS]
        lines.append(f"| **LR → LightGBM** | {' | '.join(gains)} | |")
    mean, _, gain_model, gain_features = metric_table(grid, "pr_auc")
    best = mean.stack().idxmax()
    lines += ["", "## Summary (PR-AUC, computed)", "",
              f"- Highest cell: {MODELS[best[0]]} on {best[1]}, {mean.loc[best]:.4f}.",
              f"- LR → LightGBM gain ranges from {gain_model.min():+.4f} to {gain_model.max():+.4f} across feature sets.",
              f"- F0 → F2 gain ranges from {gain_features.min():+.4f} ({MODELS[gain_features.idxmin()]}) "
              f"to {gain_features.max():+.4f} ({MODELS[gain_features.idxmax()]}) across models.",
              ""]
    return "\n".join(lines)


def main(log_path=LOG_PATH, report_path=REPORT_PATH):
    text = render(pd.read_csv(log_path), log_path)
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(text)
    return text


if __name__ == "__main__":
    print(main())
